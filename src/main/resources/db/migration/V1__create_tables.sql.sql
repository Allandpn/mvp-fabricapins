create table tb_categoria (
                              ativa boolean not null,
                              id bigint generated by default as identity,
                              nome varchar(100) not null unique,
                              descricao varchar(255) not null,
                              primary key (id)
);

create table tb_cliente (
                            ativo boolean not null,
                            data_atualizacao timestamp(6) with time zone,
                            data_cadastro timestamp(6) with time zone not null,
                            id bigint generated by default as identity,
                            usuario_id bigint unique,
                            nome varchar(150) not null,
                            email varchar(255) not null unique,
                            numero_documento varchar(255) not null unique,
                            telefone varchar(255) not null,
                            tipo_cliente varchar(255) not null check (tipo_cliente in ('VAREJO','REVENDA')),
                            tipo_pessoa varchar(255) not null check (tipo_pessoa in ('FISICA','JURIDICA')),
                            primary key (id)
);

create table tb_cupom_desconto (
                                   ativo boolean not null,
                                   data_validade date,
                                   limite_usos integer not null,
                                   quantidade_minima_itens integer,
                                   valor_desconto numeric(15,2) not null,
                                   valor_minimo_pedido numeric(15,2),
                                   data_cadastro timestamp(6) with time zone not null,
                                   id bigint generated by default as identity,
                                   codigo varchar(30) not null unique,
                                   tipo_desconto varchar(255) not null check (tipo_desconto in ('PERCENTUAL','FIXO')),
                                   primary key (id)
);

create table tb_endereco (
                             endereco_principal boolean not null,
                             cep varchar(8) not null,
                             cliente_id bigint not null,
                             data_cadastro timestamp(6) with time zone not null,
                             id bigint generated by default as identity,
                             apelido varchar(255),
                             bairro varchar(255) not null,
                             cidade varchar(255) not null,
                             complemento varchar(255),
                             estado varchar(255) not null,
                             logradouro varchar(255) not null,
                             numero varchar(255) not null,
                             observacoes varchar(255),
                             ponto_referencia varchar(255),
                             tipo_endereco varchar(255) not null check (tipo_endereco in ('ENTREGA','COBRANCA')),
                             primary key (id)
);

create table tb_item_pedido (
                                custo_unitario_snapshot numeric(38,2),
                                preco_unitario numeric(15,2) not null,
                                quantidade integer not null check (quantidade>=1),
                                id bigint generated by default as identity,
                                pedido_id bigint,
                                produto_id bigint,
                                nome_produto_snapshot varchar(150) not null,
                                img_produto_snapshot varchar(255),
                                primary key (id)
);

create table tb_opcao_frete_pedido (
                                       prazo_dias integer,
                                       valor numeric(38,2),
                                       id bigint generated by default as identity,
                                       pedido_id bigint,
                                       empresa varchar(255),
                                       nome varchar(255),
                                       provider varchar(255),
                                       service_id varchar(255),
                                       primary key (id)
);

create table tb_pagamento (
                              parcelas_cartao integer,
                              valor_pago numeric(15,2) not null,
                              data_confirmacao timestamp(6) with time zone,
                              data_pagamento timestamp(6) with time zone,
                              id bigint generated by default as identity,
                              codigo_transacao varchar(255),
                              forma_pagamento varchar(255) not null check (forma_pagamento in ('PIX','CARTAO_CREDITO')),
                              gateway_pagamento varchar(255),
                              motivo_recusa varchar(255),
                              status_pagamento varchar(255) not null check (status_pagamento in ('PENDENTE','APROVADO','RECUSADO','ESTORNADO')),
                              primary key (id)
);

create table tb_parametro (
                              id bigint generated by default as identity,
                              chave varchar(255) not null unique check (chave in ('CEP_ORIGEM','FRETE_PROVIDER_PADRAO')),
                              valor varchar(255) not null,
                              primary key (id)
);

create table tb_pedido (
                           desconto numeric(15,2),
                           prazo_entrega_dias integer,
                           valor_desconto_final numeric(38,2),
                           valor_frete numeric(15,2),
                           valor_frete_final numeric(38,2),
                           valor_subtotal numeric(15,2) not null,
                           valor_total numeric(15,2) not null,
                           valor_total_final numeric(38,2),
                           cliente_id bigint,
                           data_aguardando_envio timestamp(6) with time zone,
                           data_atualizacao timestamp(6) with time zone,
                           data_calculo_frete timestamp(6) with time zone,
                           data_cancelamento timestamp(6) with time zone,
                           data_conclusao_pedido timestamp(6) with time zone,
                           data_criacao timestamp(6) with time zone not null,
                           data_entrega timestamp(6) with time zone,
                           data_envio timestamp(6) with time zone,
                           data_fim_producao timestamp(6) with time zone,
                           data_inicio_producao timestamp(6) with time zone,
                           data_pagamento_confirmado timestamp(6) with time zone,
                           data_separacao timestamp(6) with time zone,
                           id bigint generated by default as identity,
                           pagamento_id bigint unique,
