                           nome_cliente varchar(255),
                           nome_servico_frete varchar(255),
                           numero varchar(255),
                           observacao varchar(255),
                           origem_pedido varchar(255) not null check (origem_pedido in ('SITE','WHATSAPP','REDE_SOCIAL')),
                           ponto_referencia varchar(255),
                           status_pedido varchar(255) not null check (status_pedido in ('RASCUNHO','AGUARDANDO_PAGAMENTO','PAGAMENTO_CONFIRMADO','EM_PRODUCAO','EM_SEPARACAO','AGUARDANDO_ENVIO','ENVIADO','ENTREGUE','CANCELADO','REEMBOLSADO')),
                           telefone varchar(255),
                           tipo_cliente varchar(255) check (tipo_cliente in ('VAREJO','REVENDA')),
                           primary key (id)
);

